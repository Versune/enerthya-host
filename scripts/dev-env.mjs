#!/usr/bin/env node
/**
 * Creates apps/web/.env for local development when it does not exist.
 * Never overwrites an existing file: a developer's secrets and database URL
 * must survive a `pnpm dev`.
 *
 * Next reads .env from the app directory (apps/web), not from the repo root.
 */
import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const webTarget = join(root, "apps", "web", ".env");
const workerTarget = join(root, "apps", "worker", ".env");

const DATABASE_URL = "postgres://enerthya:enerthya@127.0.0.1:5432/enerthya";
const REDIS_URL = "redis://127.0.0.1:6379";

function write(target, lines, note) {
  writeFileSync(target, [...lines, ""].join("\n"), { mode: 0o600 });
  chmodSync(target, 0o600);
  console.log(note);
}

if (!existsSync(webTarget)) {
  write(
    webTarget,
    [
      "# Generated by scripts/dev-env.mjs — local development only.",
      `DATABASE_URL=${DATABASE_URL}`,
      `REDIS_URL=${REDIS_URL}`,
      `BETTER_AUTH_SECRET=${randomBytes(32).toString("base64")}`,
      `ENCRYPTION_KEY=${randomBytes(32).toString("base64")}`,
      "BETTER_AUTH_URL=http://localhost:3000",
      "PORT=3000",
      "HOSTNAME=127.0.0.1",
    ],
    "Created apps/web/.env with generated development secrets.",
  );
}

/** Reads one KEY=value from an env file without loading the rest. */
function readValue(path, name) {
  try {
    const line = readFileSync(path, "utf8")
      .split("\n")
      .find((entry) => entry.startsWith(`${name}=`));
    return line ? line.slice(name.length + 1) : "";
  } catch {
    return "";
  }
}

if (!existsSync(workerTarget)) {
  // The worker reaches the same Postgres and Redis, and decrypts the same
  // secrets: its ENCRYPTION_KEY must be the panel's, so it is copied rather
  // than generated twice.
  const encryptionKey = readValue(webTarget, "ENCRYPTION_KEY");
  write(
    workerTarget,
    [
      "# Generated by scripts/dev-env.mjs — local development only.",
      `DATABASE_URL=${DATABASE_URL}`,
      `REDIS_URL=${REDIS_URL}`,
      `ENCRYPTION_KEY=${encryptionKey}`,
    ],
    "Created apps/worker/.env for local development.",
  );
}
