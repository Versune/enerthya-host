#!/usr/bin/env node
/**
 * Creates apps/web/.env for local development when it does not exist.
 * Never overwrites an existing file: a developer's secrets and database URL
 * must survive a `pnpm dev`.
 *
 * Next reads .env from the app directory (apps/web), not from the repo root.
 */
import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "apps", "web", ".env");

if (existsSync(target)) {
  process.exit(0);
}

const content = [
  "# Generated by scripts/dev-env.mjs — local development only.",
  "DATABASE_URL=postgres://enerthya:enerthya@127.0.0.1:5432/enerthya",
  "REDIS_URL=redis://127.0.0.1:6379",
  `BETTER_AUTH_SECRET=${randomBytes(32).toString("base64")}`,
  `ENCRYPTION_KEY=${randomBytes(32).toString("base64")}`,
  "BETTER_AUTH_URL=http://localhost:3000",
  "PORT=3000",
  "HOSTNAME=127.0.0.1",
  "",
].join("\n");

writeFileSync(target, content, { mode: 0o600 });
chmodSync(target, 0o600);
console.log("Created apps/web/.env with generated development secrets.");
