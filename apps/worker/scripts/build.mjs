#!/usr/bin/env node
/**
 * Bundles the worker into one file for the release artifact. The installer
 * runs it with plain Node — no tsx, no workspace node_modules, no TypeScript
 * on the target host. The output is CommonJS because dependencies such as
 * execa's plumbing still call require() for Node built-ins, which an ES module
 * bundle cannot resolve.
 *
 * ssh2 is aliased to a stub: dockerode requires it at load time for its ssh://
 * transport, which the worker never uses, and the real package ships a native
 * addon that cannot be bundled.
 */
import { resolve } from "node:path";
import { build } from "esbuild";

await build({
  entryPoints: ["src/index.ts"],
  outfile: "dist/index.cjs",
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node24",
  sourcemap: false,
  minify: false,
  legalComments: "none",
  alias: { ssh2: resolve(import.meta.dirname, "../src/shims/ssh2.ts") },
  banner: {
    js: "// Enerthya Host worker — generated by apps/worker/scripts/build.mjs. Do not edit.",
  },
});

console.log("apps/worker/dist/index.cjs written");
